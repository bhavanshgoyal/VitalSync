"""Generate every paper table from the experiment artifacts.

No number in the manuscript is typed by hand. Each table here reads a JSON
artifact produced by an experiment script and emits LaTeX, so a table can never
drift from the run that produced it. If an artifact is missing the table is
skipped with a visible note rather than silently omitted.

Run::

    python paper/make_tables.py
"""

from __future__ import annotations

import argparse
import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Dict, Optional

ROOT = Path(__file__).resolve().parent.parent
ARTIFACTS = ROOT / "ml-service" / "artifacts"
OUT_DIR = Path(__file__).resolve().parent / "tables"

# Backslash as a value, so LaTeX control sequences can be built without
# fighting Python escape rules inside f-strings.
B = chr(92)


def load(name: str) -> Optional[Dict]:
    path = ARTIFACTS / name
    if not path.exists():
        print(f"  [skip] {name} not found")
        return None
    return json.loads(path.read_text())


def esc(text: str) -> str:
    """Escape the LaTeX specials that actually occur in these artifacts."""
    return (str(text)
            .replace("\\", r"\textbackslash{}")
            .replace("_", r"\_")
            .replace("%", r"\%")
            .replace("&", r"\&"))


def fmt(value, digits: int = 4) -> str:
    if value is None:
        return "--"
    if isinstance(value, float):
        return f"{value:.{digits}f}"
    return esc(value)


def table_audit(audit: Dict) -> str:
    """Track A: the label is a rule, and the vitals carry nothing."""
    rows = []
    for name, r in audit["milestone_models"].items():
        rows.append(f"{esc(name)} & {fmt(r['accuracy'], 5)} & {fmt(r['macro_f1'], 5)} \\\\")

    rule = audit["candidate_rule"]
    abl = audit["ablation_vitals_only"]

    return f"""% generated by paper/make_tables.py -- do not edit
\\begin{{table}}[t]
\\caption{{Track A. Classification on the public vital-signs dataset, and the
recovered label rule. Scores approach the ceiling because the published label is
a deterministic function of heart rate and BMI, not because vital signs predict
risk.}}
\\label{{tab:audit}}
\\centering
\\begin{{tabular}}{{lrr}}
\\toprule
Model & Accuracy & Macro-F1 \\\\
\\midrule
{chr(10).join(rows)}
\\midrule
Recovered rule & {fmt(rule['accuracy'], 5)} & -- \\\\
Vitals-only ablation & {fmt(abl['accuracy'], 5)} & {fmt(abl['macro_f1'], 5)} \\\\
Majority-class baseline & {fmt(abl['majority_class_baseline'], 5)} & -- \\\\
\\bottomrule
\\end{{tabular}}

\\vspace{{2pt}}
\\footnotesize Rule: \\texttt{{{esc(rule['expression'])}}}, exact on
{audit['dataset']['rows']:,} of {audit['dataset']['rows']:,} rows
({rule['mismatches']} mismatches). The ablation uses only
SpO$_2$, blood pressure, temperature and respiratory rate, and does not beat the
majority-class baseline.
\\end{{table}}
"""


def table_trackb(metrics: Dict) -> str:
    """Track B: model vs rule, with the safety columns beside macro-F1."""
    rows = []
    for r in metrics["results"]:
        clin = r.get("clinical", {})
        rows.append(
            f"{esc(r['model'])} & {fmt(r['accuracy'])} & {fmt(r['macro_f1'])} & "
            f"{fmt(clin.get('high_recall'))} & {fmt(clin.get('missed_high_rate'))} & "
            f"{fmt(clin.get('mean_cost'))} \\\\")

    cmp = metrics.get("selection_criteria_comparison", {})
    note = ""
    if cmp and not cmp.get("criteria_agree", True):
        note = (f"Macro-F1 selects \\texttt{{{esc(cmp['by_macro_f1'])}}} while the "
                f"asymmetric-cost criterion selects "
                f"\\texttt{{{esc(cmp['by_mean_cost'])}}}; the F1-optimal model "
                f"carries the higher rate of HIGH observations reported as LOW.")

    return f"""% generated by paper/make_tables.py -- do not edit
\\begin{{table*}}[t]
\\caption{{Track B. Recovering the clean-signal NEWS2 band from sensor-corrupted
telemetry. All rows see the same corrupted observations. Missed-HIGH is the
fraction of HIGH observations reported as LOW.}}
\\label{{tab:trackb}}
\\centering
\\begin{{tabular}}{{lrrrrr}}
\\toprule
Model & Accuracy & Macro-F1 & HIGH recall & Missed-HIGH & Mean cost \\\\
\\midrule
{chr(10).join(rows)}
\\bottomrule
\\end{{tabular}}

\\vspace{{2pt}}
\\footnotesize Cohort: {metrics['cohort']['rows']:,} readings from
{metrics['cohort']['n_patients']:,} simulated patients, split by patient.
Selection metric: \\texttt{{{esc(metrics['selection_metric'])}}}. {note}
Cost weights are a stated assumption, not derived from outcome data.
\\end{{table*}}
"""


def table_noise_sweep(bench: Dict) -> str:
    sweep = bench.get("noise_sweep")
    if not sweep:
        return ""
    model = bench.get("sweep_model", "model")
    rows = []
    for cell in sweep["matched_train_test_noise"]:
        rule = cell["news2_rule_on_observed"]["macro_f1"]
        mdl = cell[model]["macro_f1"]
        delta = cell["delta_macro_f1_model_minus_rule"]
        marker = "" if cell.get("delta_excludes_zero") else "$^{\\dagger}$"
        rows.append(
            f"{cell['noise_scale']:.1f} & "
            f"{fmt(rule['mean'])} & {fmt(mdl['mean'])} & "
            f"{delta['mean']:+.4f}{marker} & "
            f"[{delta['ci95_low']:+.4f}, {delta['ci95_high']:+.4f}] \\\\")

    return f"""% generated by paper/make_tables.py -- do not edit
\\begin{{table}}[t]
\\caption{{Macro-F1 against sensor-noise scale, mean over
{sweep['n_seeds']} independent cohort seeds. At $\\sigma=0$ the observation
equals the latent signal, so the rule is exact and the learned model cannot
improve on it; the advantage appears only once observations are corrupted.}}
\\label{{tab:noise}}
\\centering
\\begin{{tabular}}{{rrrrl}}
\\toprule
$\\sigma$ & NEWS2 rule & {esc(model)} & $\\Delta$ & 95\\% CI \\\\
\\midrule
{chr(10).join(rows)}
\\bottomrule
\\end{{tabular}}

\\vspace{{2pt}}
\\footnotesize $^{{\\dagger}}$ interval includes zero; the difference is not
resolved at this number of seeds.
\\end{{table}}
"""


def table_latency(bench: Dict) -> str:
    lat = bench.get("latency", {}).get("single_prediction_ms")
    if not lat:
        return ""
    return f"""% generated by paper/make_tables.py -- do not edit
\\begin{{table}}[t]
\\caption{{Triage inference latency, {lat['n']} single-observation predictions.
In-process model call only: excludes HTTP, serialisation and network transit.}}
\\label{{tab:latency}}
\\centering
\\begin{{tabular}}{{lr}}
\\toprule
Statistic & Milliseconds \\\\
\\midrule
Mean & {fmt(lat['mean'], 3)} \\\\
p50 & {fmt(lat['p50'], 3)} \\\\
p95 & {fmt(lat['p95'], 3)} \\\\
p99 & {fmt(lat['p99'], 3)} \\\\
Maximum & {fmt(lat['max'], 3)} \\\\
\\bottomrule
\\end{{tabular}}

\\vspace{{2pt}}
\\footnotesize Measured on one developer workstation. Not a service-level
objective.
\\end{{table}}
"""


def table_calibration(metrics: Dict) -> str:
    cal = metrics.get("calibration")
    if not cal:
        return ""
    rows = []
    for b in cal["bins"]:
        if not b["count"]:
            continue
        rows.append(
            # Braced: a leading "[" after \ is otherwise parsed as \[len].
            f"{{}}[{b['bin_lower']:.1f}, {b['bin_upper']:.1f}] & {b['count']:,} & "
            f"{fmt(b['mean_confidence'], 3)} & {fmt(b['accuracy'], 3)} & "
            f"{b['signed_gap']:+.3f} \\\\")

    return f"""% generated by paper/make_tables.py -- do not edit
\\begin{{table}}[t]
\\caption{{Calibration of the selected triage model. A positive gap means stated
confidence exceeds observed accuracy in that bin.}}
\\label{{tab:calibration}}
\\centering
\\begin{{tabular}}{{lrrrr}}
\\toprule
Confidence bin & $n$ & Mean conf. & Accuracy & Gap \\\\
\\midrule
{chr(10).join(rows)}
\\bottomrule
\\end{{tabular}}

\\vspace{{2pt}}
\\footnotesize ECE {fmt(cal['ece'], 4)}, MCE {fmt(cal['mce'], 4)},
Brier {fmt(cal['brier_score'], 4)}, overall over-confidence
{cal['overconfidence']:+.4f}.
\\end{{table}}
"""


def table_wearable(abl: Dict) -> str:
    if not abl:
        return ""
    rows = []
    labels = {
        "S1_full_observation": "Full observation (reported setting)",
        "S2_trained_full_served_wearable_only": "Trained full, served wearable-only",
        "S3_trained_and_served_wearable_only": "Trained and served wearable-only",
    }
    for key, r in abl["scenarios"].items():
        rows.append(
            f"{labels.get(key, esc(key))} & {fmt(r['macro_f1'])} & "
            f"{fmt(r['high_recall'])} & {fmt(r['missed_high_rate'])} \\\\")

    cost = abl["cost_of_silent_mismatch"]
    return f"""% generated by paper/make_tables.py -- do not edit
\\begin{{table}}[t]
\\caption{{Wearable-only deployment ablation. Supplemental oxygen and AVPU are
NEWS2 parameters that a wearable cannot supply.}}
\\label{{tab:wearable}}
\\centering
\\begin{{tabular}}{{lrrr}}
\\toprule
Scenario & Macro-F1 & HIGH recall & Missed-HIGH \\\\
\\midrule
{chr(10).join(rows)}
\\bottomrule
\\end{{tabular}}

\\vspace{{2pt}}
\\footnotesize Serving the fully-trained model on a wearable-only feed costs
{cost['macro_f1_drop']:+.4f} macro-F1 and raises missed-HIGH by
{cost['missed_high_rate_increase']:+.4f}.
\\end{{table}}
"""


def table_llm(llm: Dict) -> str:
    """E9. Returns empty until a live LLM tier has actually been run."""
    if not llm or llm.get("deterministic_only"):
        return ""

    rows = []
    for name, e in llm["by_provider"].items():
        rate = e["faithfulness_rate"]
        p50 = e["summary_latency_ms"].get("p50")
        rate_txt = f"{rate:.3f}" if rate is not None else "--"
        p50_txt = f"{p50:.1f}" if p50 is not None else "--"
        share = e["share_of_assessments"] * 100
        rows.append(
            f"{esc(name)} & {e['answered']} & "
            f"{share:.1f}\\% & {rate_txt} & {p50_txt} \\\\"
        )

    tiers = esc(", ".join(llm["llm_tiers_enabled"]))
    return f"""% generated by paper/make_tables.py -- do not edit
\\begin{{table}}[t]
\\caption{{Live summarization tiers over {llm['cases']} cases spanning
the severity range. Faithfulness is the share of summaries from a tier citing
only supplied numbers and naming no condition.}}
\\label{{tab:llm}}
\\centering
\\begin{{tabular}}{{lrrrr}}
\\toprule
Tier & Answered & Share & Faithfulness & p50 (ms) \\\\
\\midrule
{chr(10).join(rows)}
\\bottomrule
\\end{{tabular}}

\\vspace{{2pt}}
\\footnotesize Tiers enabled: {tiers}. A tier that produced an unfaithful
summary was overridden at request time, so this counts how often the guard
fired, not how often a bad summary reached a reader. Faithfulness checking is
necessary, not sufficient: it cannot detect a fluent, numerically correct,
clinically wrong reading of the data.
\\end{{table}}
"""

def table_events(events: Dict) -> str:
    """E6. Short policy labels: the full definitions overflow a single column."""
    if not events:
        return ""
    p = events["policies"]
    rows = [
        ("A. Per-parameter thresholds", p["A_per_parameter_thresholds"]),
        ("B. Aggregate band", p["B_aggregate_band"]),
        ("C. Band transition", p["C_band_transition"]),
    ]
    body = chr(10).join(
        f"{label} & {d['events']:,} & {d['events_per_100_readings']:.2f} " + B * 2
        for label, d in rows
    )

    return f"""% generated by paper/make_tables.py -- do not edit
{B}begin{{table}}[t]
{B}caption{{Notification event counts over {events['cohort']['total_readings']:,}
simulated readings. A emits one event per breaching parameter per reading; B one
per reading whose band is not LOW; C one per upward band transition per patient.
This is event arithmetic only.}}
{B}label{{tab:events}}
{B}centering
{B}begin{{tabular}}{{lrr}}
{B}toprule
Policy & Events & Per 100 {B*2}
{B}midrule
{body}
{B}bottomrule
{B}end{{tabular}}

{B}vspace{{2pt}}
{B}footnotesize {B}textbf{{These counts are not a measurement of alert
fatigue, clinician workload, or patient benefit.}} Policy C emits fewer
notifications by construction; whether that is clinically safe is untested here.
{B}end{{table}}
"""


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Generate LaTeX tables from artifacts")
    ap.add_argument("--out-dir", default=str(OUT_DIR))
    args = ap.parse_args(argv)

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    audit = load("audit.json")
    metrics = load("metrics.json")
    bench = load("benchmark.json")
    wearable = load("wearable_ablation.json")
    events = load("alert_compression.json")
    llm = load("llm_evaluation.json")

    generated = {}
    if audit:
        generated["table_audit.tex"] = table_audit(audit)
    if metrics:
        generated["table_trackb.tex"] = table_trackb(metrics)
        generated["table_calibration.tex"] = table_calibration(metrics)
    if bench:
        generated["table_noise.tex"] = table_noise_sweep(bench)
        generated["table_latency.tex"] = table_latency(bench)
    if wearable:
        generated["table_wearable.tex"] = table_wearable(wearable)
    if events:
        generated["table_events.tex"] = table_events(events)
    if llm:
        generated["table_llm.tex"] = table_llm(llm)

    written = []
    for name, content in generated.items():
        if not content.strip():
            continue
        (out_dir / name).write_text(content, encoding="utf-8")
        written.append(name)
        print(f"  [ok] {name}")

    manifest = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "tables": written,
        "source_artifacts": [
            n for n, v in [
                ("audit.json", audit), ("metrics.json", metrics),
                ("benchmark.json", bench), ("wearable_ablation.json", wearable),
                ("alert_compression.json", events),
                ("llm_evaluation.json", llm),
            ] if v
        ],
        "note": "Every table is generated. Do not edit the .tex files by hand.",
    }
    (out_dir / "manifest.json").write_text(json.dumps(manifest, indent=2))
    print(f"\n{len(written)} tables written to {out_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
